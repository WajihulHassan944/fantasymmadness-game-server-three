'use strict';
const assert=require('node:assert/strict');
const {createRecruit,makeLink,verifyPaidEntry,report}=require('./growth-affiliate-attribution');
const affiliates=new Map(),entries=new Map();
const pending=createRecruit({id:'aff-1',name:'Kelise Davis',consent:false,approved:true});
assert.equal(pending.status,'pending');
assert.throws(()=>makeLink(pending,'fight-1'),/Unapproved/);
const affiliate=createRecruit({id:'aff-1',name:'Kelise Davis',consent:true,approved:true});
affiliates.set(affiliate.id,affiliate);
assert.equal(makeLink(affiliate,'fight-1'),'/affiliate/kelise-davis?fight=fight-1');
assert.equal(affiliate.outreachSent,false,'no outbound messaging');
const base={type:'paid_entry',verified:true,paymentStatus:'settled',entryId:'entry-1',playerId:'player-1',fightId:'fight-1',affiliateId:'aff-1',referralAffiliateId:'aff-1',amountCents:500};
assert.equal(verifyPaidEntry({...base,verified:false},{affiliates,entries}).credited,false);
assert.equal(verifyPaidEntry({...base,paymentStatus:'pending'},{affiliates,entries}).credited,false);
assert.equal(verifyPaidEntry({...base,referralAffiliateId:'aff-other'},{affiliates,entries}).credited,false);
assert.equal(entries.size,0,'no false attribution');
assert.equal(verifyPaidEntry(base,{affiliates,entries}).credited,true);
assert.equal(verifyPaidEntry(base,{affiliates,entries}).reason,'duplicate_entry');
assert.deepEqual(report(entries),{'aff-1':{paidEntries:1,revenueCents:500}});
assert.equal(verifyPaidEntry({...base,entryId:'entry-2',affiliateId:'unknown',referralAffiliateId:'unknown'},{affiliates,entries}).reason,'unapproved_affiliate');
console.log('PASS synthetic affiliate recruit, consent gate, short link, verified settled paid entry, dedup, revenue attribution, rejected fraud scenarios');
