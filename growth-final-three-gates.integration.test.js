'use strict';
const assert=require('node:assert/strict');
const {deliveryReceipt,conversionProof,launchGate}=require('./growth-final-three-gates');
const draft={id:'synthetic-pr-1',channel:'email'};
const approval={draftId:draft.id,ownerApproved:true};
assert.equal(deliveryReceipt({draft,providerResult:{sandbox:true,accepted:true,messageId:'fake'}}).ok,false);
assert.equal(deliveryReceipt({draft,approval,providerResult:{accepted:true,messageId:'fake'}}).ok,false);
assert.equal(deliveryReceipt({draft,approval,providerResult:{sandbox:true,accepted:true}}).ok,false);
const sandboxReceipt=deliveryReceipt({draft,approval,providerResult:{sandbox:true,accepted:true,messageId:'synthetic-provider-receipt'}});
assert.equal(sandboxReceipt.ok,true);
assert.equal(sandboxReceipt.receipt.realDelivery,false);
const affiliate={id:'affiliate-1',status:'approved'};
const referral={affiliateId:'affiliate-1',playerId:'player-1',fightId:'fight-1'};
const entry={id:'entry-1',playerId:'player-1',fightId:'fight-1',status:'accepted',paid:true};
const payment={source:'server_verified',status:'settled',transactionId:'synthetic-tx',entryId:'entry-1',playerId:'player-1',amountCents:500};
const signup={source:'server_verified',status:'created',playerId:'player-1'};
assert.equal(conversionProof({affiliate,referral,entry,payment}).ok,false);
assert.equal(conversionProof({signup:{...signup,source:'public_analytics'},affiliate,referral,entry,payment}).ok,false);
assert.equal(conversionProof({signup,affiliate,referral,entry,payment:{...payment,status:'pending'}}).ok,false);
assert.equal(conversionProof({signup,affiliate,referral,entry,payment,existingCredit:true}).ok,false);
assert.equal(conversionProof({signup,affiliate,referral,entry,payment}).ok,true);
assert.equal(launchGate({serviceReceipts:[sandboxReceipt],conversionVerified:true,securityReview:true,rollbackRehearsed:true,monitoringVerified:true}).ready,false,'owner signoff mandatory');
assert.equal(launchGate().ready,false);
const hypothetical=launchGate({serviceReceipts:[sandboxReceipt],conversionVerified:true,securityReview:true,rollbackRehearsed:true,ownerApproved:true,monitoringVerified:true});
assert.equal(hypothetical.ready,true,'only all explicit evidence gates permit a hypothetical approval');
console.log('PASS final-three CONTRACT tests: sandbox receipts, signup-to-settled-payment reconciliation, approval/rollback/monitoring gates. Real services NOT verified.');
